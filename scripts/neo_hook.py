#!/usr/bin/env python3
"""Claude Code hook for Neo coordination.

  python3 scripts/neo_hook.py pre    # PreToolUse for Edit/Write: declare intent, block if queued
  python3 scripts/neo_hook.py post   # PostToolUse for Edit/Write: complete work, release the lock
  python3 scripts/neo_hook.py read   # PostToolUse for Read: save what this session saw

Each Claude Code session names itself with the NEO_DEVELOPER environment variable.
Without it the hook does nothing, so other sessions are unaffected.
Optional NEO_INTENT sets the intent text; the default is "Edit <file>".

Exit code 2 blocks the tool call and shows the message to the session.
"""

import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from core.activity_log import log_activity  # noqa: E402
from core.freshness import record_read  # noqa: E402
from core.lock_manager import LockManager  # noqa: E402
from core.pre_gen_check import check_for_conflicts  # noqa: E402


def _relative_file_path(hook_input):
    path = (hook_input.get("tool_input") or {}).get("file_path")
    if not path:
        return None
    try:
        return str(Path(path).resolve().relative_to(REPO))
    except ValueError:
        return path


def pre(developer, file_path):
    intent = os.environ.get("NEO_INTENT") or f"Edit {file_path}"
    _risk, _msg, lock_info = check_for_conflicts(
        agent_id=developer, file_path=file_path, intent=intent, region=None
    )
    holder = (lock_info or {}).get("lock_holder")

    if holder and holder != developer:
        log_activity(
            developer_id=developer, file_path=file_path, intent=intent,
            lock_state="WAITING", lock_holder=holder,
            queue_position=(lock_info or {}).get("queue_position"),
            waiting_for=holder,
        )
        print(
            f"Neo: {file_path} is locked by {holder}. You are queued behind them. "
            f"Do not edit this file until {holder} completes.",
            file=sys.stderr,
        )
        return 2

    log_activity(
        developer_id=developer, file_path=file_path, intent=intent,
        lock_state="ACQUIRED" if holder == developer else None, lock_holder=holder,
    )
    return 0


def read(developer, file_path):
    record_read(developer, file_path)
    return 0


def post(developer, file_path):
    release = LockManager().release_lock(file_path, None, developer)
    log_activity(
        developer_id=developer, file_path=file_path,
        intent=f"Work completed on {file_path}", intent_category="completion",
    )
    nxt = release.get("next_lock_holder")
    if nxt:
        print(f"Neo: released {file_path}. {nxt} is next in the queue.", file=sys.stderr)
    return 0


def main(argv):
    mode = argv[1] if len(argv) > 1 else ""
    developer = os.environ.get("NEO_DEVELOPER")
    try:
        hook_input = json.loads(sys.stdin.read() or "{}")
    except json.JSONDecodeError:
        return 0
    file_path = _relative_file_path(hook_input)
    if not developer or not file_path or mode not in ("pre", "post", "read"):
        return 0
    if mode == "read":
        return read(developer, file_path)
    return pre(developer, file_path) if mode == "pre" else post(developer, file_path)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
